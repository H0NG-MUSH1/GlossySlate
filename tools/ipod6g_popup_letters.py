#!/usr/bin/env python3
# Renders the letters of the fast scroll popup (A-Z and #) into
# apps/gui/popup_letters.h for apps/gui/popup.c (IPOD_6G):
#
#   python3 tools/ipod6g_popup_letters.py path/to/LiberationSans-Bold.ttf
#
# The letters are Liberation Sans 2 Bold (SIL Open Font License 1.1), the
# typeface the GlossySlate fonts are made from, 72 px, for a square panel of
# 112 x 112 (the panel parts of the popups, height 112). Every letter is
# centred on its ink horizontally; the cap height of "H" is centred
# vertically, so all letters share one baseline. popup.c draws them in the
# light symbol colour of the popups (#DFE6F3).
#
# A letter is a 4 bit alpha mask of its ink box, row by row, two pixels per
# byte (the left one in the high nibble), every row padded to whole bytes,
# with the place of the box in the panel. Needs Pillow.

import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'apps', 'gui', 'popup_letters.h')

PANEL = 112          # the square panel, a height of the panel parts
SIZE = 72            # font size in pixels
LETTERS = [chr(c) for c in range(ord('A'), ord('Z') + 1)] + ['#']


def render(font, ch):
    """ch on the panel: (x, y, w, h, rows of 4 bit values)"""
    cap = font.getbbox('H')
    ink = font.getbbox(ch)
    tx = round((PANEL - (ink[2] - ink[0])) / 2 - ink[0])
    ty = round((PANEL - (cap[3] - cap[1])) / 2 - cap[1])
    im = Image.new('L', (PANEL, PANEL), 0)
    ImageDraw.Draw(im).text((tx, ty), ch, font=font, fill=255)
    box = im.getbbox()
    x0, y0, x1, y1 = box
    px = im.load()
    rows = [[(px[x, y] * 15 + 127) // 255 for x in range(x0, x1)] for y in range(y0, y1)]
    return x0, y0, x1 - x0, y1 - y0, rows


def pack(rows):
    out = bytearray()
    for row in rows:
        r = row + [0] * (len(row) & 1)
        for i in range(0, len(r), 2):
            out.append((r[i] << 4) | r[i + 1])
    return out


def name(ch):
    return 'hash' if ch == '#' else ch


def main():
    if len(sys.argv) != 2:
        sys.exit('usage: %s LiberationSans-Bold.ttf' % sys.argv[0])
    font = ImageFont.truetype(sys.argv[1], SIZE)
    lines = ['/* Letters of the fast scroll popup (A-Z, #): Liberation Sans 2 Bold',
             ' * (SIL Open Font License 1.1), %d px, for a square panel of %d x %d.' % (SIZE, PANEL, PANEL),
             ' * Generated by tools/ipod6g_popup_letters.py - do not edit. */',
             '#ifndef POPUP_LETTERS_H', '#define POPUP_LETTERS_H', '',
             '#define POPUP_LETTER_PANEL %d' % PANEL, '',
             '/* a 4 bit alpha mask: rows of (w + 1) / 2 bytes, the left pixel in the',
             ' * high nibble; x, y: its place in the panel */',
             'struct popup_glyph {', '    unsigned char x, y, w, h;', '    const unsigned char *mask;', '};', '']
    table = []
    total = 0
    for ch in LETTERS:
        x, y, w, h, rows = render(font, ch)
        data = pack(rows)
        total += len(data)
        lines.append('static const unsigned char popup_glyph_%s[%d] = {' % (name(ch), len(data)))
        for i in range(0, len(data), 16):
            lines.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
        lines.append('};')
        table.append('    { %d, %d, %d, %d, popup_glyph_%s },   /* %s */' % (x, y, w, h, name(ch), ch))
    lines += ['', "/* 'A' .. 'Z', then '#' */",
              'static const struct popup_glyph popup_letters[%d] = {' % len(LETTERS)] + table + ['};', '',
              '#endif', '']
    open(OUT, 'w').write('\n'.join(lines))
    print('%d letters, %d bytes of masks -> %s' % (len(LETTERS), total, os.path.relpath(OUT)))


if __name__ == '__main__':
    main()
