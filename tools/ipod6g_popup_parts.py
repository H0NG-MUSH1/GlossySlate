#!/usr/bin/env python3
# Turns the parts of the GlossySlate popups (GlossySlate/firmware-assets/
# popups/*.png, from the designer's handover) into apps/gui/popup_parts.h for
# apps/gui/popup.c (IPOD_6G):
#
#   python3 tools/ipod6g_popup_parts.py
#
# Every part becomes RGB565 plus 8 bit alpha. The firmware blends it with
# the screen itself, with an ordered dither; the 4 bit alpha of the skin
# engine would show the soft shadows as bands. The right end of a panel is
# the left one mirrored (the PNGs differ by at most 4 of 255), so only the
# left end is stored. No Pillow needed.

import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'GlossySlate', 'firmware-assets', 'popups')
OUT = os.path.join(HERE, '..', 'apps', 'gui', 'popup_parts.h')

HEIGHTS = (40, 56, 72, 88, 96, 104, 112, 120, 128)
# only the symbols popup.c shows (info, locked and unlocked are unused:
# the key lock has no popup)
SYMBOLS = ('done', 'warning')


def read_png_rgba(path):
    d = open(path, 'rb').read()
    assert d[:8] == b'\x89PNG\r\n\x1a\n', path
    p, idat = 8, b''
    while p < len(d):
        n, t = struct.unpack('>I4s', d[p:p + 8])
        body = d[p + 8:p + 8 + n]
        p += 12 + n
        if t == b'IHDR':
            w, h, depth, ctype, _, _, inter = struct.unpack('>IIBBBBB', body)
        elif t == b'IDAT':
            idat += body
    assert depth == 8 and inter == 0 and ctype in (2, 6), path
    bpp = 4 if ctype == 6 else 3
    raw = zlib.decompress(idat)
    stride = w * bpp
    prev = bytearray(stride)
    rows, i = [], 0
    for _ in range(h):
        f = raw[i]
        line = bytearray(raw[i + 1:i + 1 + stride])
        i += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pr = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[x] = (line[x] + pr) & 255
        rows.append([tuple(line[x * bpp:x * bpp + bpp]) + ((255,) if bpp == 3 else ())
                     for x in range(w)])
        prev = line
    return w, h, rows


def rgb565(r, g, b):
    return (((r * 31 + 127) // 255) << 11) | (((g * 63 + 127) // 255) << 5) | ((b * 31 + 127) // 255)


def part(name):
    w, h, rows = read_png_rgba(os.path.join(SRC, name + '.png'))
    rgb, alpha = [], []
    for row in rows:
        for r, g, b, a in row:
            rgb.append(rgb565(r, g, b) if a else 0)
            alpha.append(a)
    return w, h, rgb, alpha


def c_array(ctype, name, values, per_line=12, fmt='0x%04x'):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append('    ' + ', '.join(fmt % v for v in values[i:i + per_line]) + ',')
    return 'static const %s %s[%d] = {\n%s\n};\n' % (ctype, name, len(values), '\n'.join(lines))


def main():
    out = ['/* Parts of the GlossySlate popups for apps/gui/popup.c, RGB565 and 8 bit',
           ' * alpha. Generated by tools/ipod6g_popup_parts.py from',
           ' * GlossySlate/firmware-assets/popups - do not edit. */',
           '#ifndef POPUP_PARTS_H', '#define POPUP_PARTS_H', '',
           'struct popup_part {', '    short width, height;',
           '    const unsigned short *rgb;   /* RGB565 */',
           '    const unsigned char *alpha;  /* 0 transparent .. 255 opaque */', '};', '']
    tables = {}
    total = 0

    def add(cname, src):
        nonlocal total
        w, h, rgb, alpha = part(src)
        total += len(rgb) * 3
        out.append(c_array('unsigned short', cname + '_rgb', rgb))
        out.append(c_array('unsigned char', cname + '_a', alpha, 16, '%3d'))
        return '{ %d, %d, %s_rgb, %s_a }' % (w, h, cname, cname)

    left, mid = [], []
    for hh in HEIGHTS:
        left.append(add('popup_panel%d_l' % hh, 'panel_h%d_left' % hh))
        mid.append(add('popup_panel%d_m' % hh, 'panel_h%d_middle' % hh))
    tables['popup_panel_left'] = left
    tables['popup_panel_mid'] = mid
    for key, src in (('popup_track', 'bar_track'), ('popup_fill', 'bar_fill'),
                     ('popup_key_yes', 'button_yes'), ('popup_key_no', 'button_no')):
        tables[key] = [add('%s_%s' % (key, s), '%s_%s' % (src, t))
                       for s, t in (('l', 'left'), ('m', 'middle'), ('r', 'right'))]
    tables['popup_symbols'] = [add('popup_sym_' + s, 'symbol_' + s) for s in SYMBOLS]

    out.append('/* panel heights (without shadow) of popup_panel_left/_mid */')
    out.append('static const short popup_panel_heights[%d] = { %s };\n'
               % (len(HEIGHTS), ', '.join(str(h) for h in HEIGHTS)))
    out.append('/* bar, keys: left, middle, right; symbols: enum popup_symbol */')
    for name, items in tables.items():
        out.append('static const struct popup_part %s[%d] = {\n    %s\n};\n'
                   % (name, len(items), ',\n    '.join(items)))
    out.append('enum popup_symbol { %s };\n' % ', '.join('POPUP_SYM_' + s.upper() for s in SYMBOLS))
    out.append('#endif')
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print('%s: %d KB' % (os.path.relpath(OUT), total // 1024))


if __name__ == '__main__':
    sys.exit(main())
