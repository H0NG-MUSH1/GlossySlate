"""The back of the cover in PictureFlow ("Cover Flow", DESIGN.md 5.14):

    python3 tools/build_pictureflow.py

tools/pictureflow/parts.json is the designer's export: sizes, the colour of
every row of the gradients, turn values. All parts are the same in every
column, so the plugin needs no pictures: this writes their rows as tables
into apps/plugins/pictureflow/pictureflow_glossy.h, which the plugin composes
and dithers itself. Not used from the design: the background made from the
cover (the cover flow stays visible around the back) and the scroll bar
(the plugin draws the knob of the lists instead). The speaker at the
playing title is the one of the database lists (tools/ipod6g_list_marks.py).

It also writes the default cover of Cover Flow into the theme,
.rockbox/wps/glossyslate/cover_flow.bmp: the default cover
(firmware-assets/albumart_list_default_512.png) as large as PictureFlow's
slides (128 x 128 at 320 x 240), opaque, without corners or reflection
(PictureFlow adds its own). Scaled in full precision and quantised to
RGB565 once with a 4 x 4 ordered dither, as build_wps_cover.py does, so the
grey ground shows no tinted bands. The plugin uses it for albums without a
picture instead of its "?" slide.
Pure Python.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(HERE, 'pictureflow')
OUT = os.path.join(ROOT, 'apps', 'plugins', 'pictureflow', 'pictureflow_glossy.h')
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(ROOT, 'tools'))
sys.path.insert(0, HERE)
import ipod6g_list_marks as marks  # noqa: E402
import build_wps_cover as cover  # noqa: E402

# DISPLAY_WIDTH of pictureflow.c at 320 x 240: MAX(240 / 2, 320 * 2 / 5);
# a square cover fills the slide's width
COVER_SIZE = 128
COVER_NAME = 'cover_flow.bmp'


def default_cover():
    """the default cover for albums without a picture, dithered at the
    slide's own pixels (the slide moves, so no screen position counts)"""
    src = cover.scaled_source(COVER_SIZE)
    rows = []
    for y, line in enumerate(src):
        row = []
        for x, rgb in enumerate(line):
            t = (cover.BAYER[y & 3][x & 3] + 0.5) / 16.0
            row.append(cover.rgb888([max(0, min(m, int(v * m / 255.0 + t)))
                                     for v, m in zip(rgb, (31, 63, 31))]))
        rows.append(row)
    path = os.path.join(cover.PKG, COVER_NAME)
    old = open(path, 'rb').read() if os.path.exists(path) else None
    cover.write_bmp24(path, rows)
    new = open(path, 'rb').read()
    print('written' if old != new else 'unchanged', os.path.relpath(path),
          '(%d x %d)' % (COVER_SIZE, COVER_SIZE))


def table(name, ctype, rows, comment):
    dims = '[%d]' % len(rows)
    if isinstance(rows[0], (list, tuple)):
        dims += '[%d]' % len(rows[0])
        body = ',\n'.join('    { %s }' % ', '.join('%3d' % v for v in r) for r in rows)
    else:
        body = '    ' + ', '.join('%3d' % v for v in rows)
    return '/* %s */\nstatic const %s %s%s = {\n%s\n};\n' % (comment, ctype, name, dims, body)


def main():
    p = json.load(open(os.path.join(SRC, 'parts.json'), encoding='utf-8'))
    rows = p['streifen_rgba']
    m = p['masse']
    turn = p['drehung']
    single = lambda k: rows[k][0]
    assert all(r == rows['liste'][0] for r in rows['liste'])
    assert all(r == rows['streifen'][0] for r in rows['streifen'])

    card = m['karte_rueckseite']
    field = m['feld']

    out = ['/* Generated by GlossySlate/tools/build_pictureflow.py from',
           ' * GlossySlate/tools/pictureflow/ -- do not edit. The back of the cover',
           ' * in PictureFlow ("Cover Flow", GlossySlate/DESIGN.md 5.14). */',
           '#ifndef PICTUREFLOW_GLOSSY_H', '#define PICTUREFLOW_GLOSSY_H', '']
    defs = [
        ('PFG_CARD_X', card[0]), ('PFG_CARD_Y', card[1]),
        ('PFG_CARD_W', card[2]), ('PFG_CARD_H', card[3]),
        ('PFG_FIELD_X', field[0]), ('PFG_FIELD_Y', field[1]),
        ('PFG_FIELD_W', field[2]),
        ('PFG_HEAD_H', m['kopf_hoehe']), ('PFG_ROW_H', m['zeile_hoehe']),
        ('PFG_ROWS', m['zeilen']), ('PFG_LIST_Y', m['liste_y']),
        ('PFG_TEXT_X', m['text_x']), ('PFG_TITLE_W', m['titel_breite']),
        ('PFG_TIME_RIGHT', m['dauer_rechts']),
        ('PFG_CAM_DIST', int(turn['cam_dist'])),
        ('PFG_FRAMES_LOOSEN', turn['bilder_loesen']),
        ('PFG_FRAMES_TURN', turn['bilder_drehen']),
        # the back card: centre and size, x2 so that 133.5 stays exact
        ('PFG_BACK_CX2', round(turn['rueckseite']['mitte'][0] * 2)),
        ('PFG_BACK_CY2', round(turn['rueckseite']['mitte'][1] * 2)),
    ]
    out += ['#define %-20s %d' % d for d in defs] + ['']
    out.append(table('pfg_head', 'unsigned char', rows['kopf'],
                     'head of the field, rows %d.. of the screen: r, g, b, alpha'
                     % field[1]))
    out.append(table('pfg_list', 'unsigned char', single('liste'),
                     'surface of the list: r, g, b, alpha'))
    out.append(table('pfg_stripe', 'unsigned char', single('streifen'),
                     'grey stripe of every second title: r, g, b, alpha'))
    out.append(table('pfg_select', 'unsigned char', [r[:3] for r in rows['auswahl']],
                     'the selected row, opaque: r, g, b'))
    w, h = 14, 12               # LIST_SPEAKER_W/H of apps/gui/bitmap/list.c
    out += ['#define PFG_SPEAKER_W %d' % w, '#define PFG_SPEAKER_H %d' % h, '']
    out.append(table('pfg_speaker', 'unsigned char',
                     marks.nibbles(marks.render(w, h, marks.speaker)),
                     'the speaker of the database lists: 4 bit alpha, 0 opaque .. 15 clear,\n'
                     ' * the first pixel in the lower nibble (list_speaker_mask)'))
    out += ['#endif', '']
    data = '\n'.join(out)
    old = open(OUT).read() if os.path.exists(OUT) else None
    if old != data:
        open(OUT, 'w').write(data)
    print('written' if old != data else 'unchanged', os.path.relpath(OUT))
    default_cover()


if __name__ == '__main__':
    main()
